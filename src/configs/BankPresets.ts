export function presetByIcon(icon: string): BankPreset | undefined {
    return BANK_PRESETS.find((preset) => preset.icon === icon);
}

export function presetByName(name: string): BankPreset | undefined {
    const text = (name || "").trim();
    if (!text) {
        return undefined;
    }
    const exact = BANK_PRESETS.find((preset) => preset.name === text);
    if (exact) {
        return exact;
    }
    return BANK_PRESETS.find((preset) =>
        preset.keywords.some((keyword) => keyword.length >= 2 && text.includes(keyword))
    );
}

export function resolveBankPreset(icon: string, name: string): BankPreset | undefined {
    return presetByIcon(icon) || presetByName(name);
}
